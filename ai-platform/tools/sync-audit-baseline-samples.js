const files = fs.readdirSync(path.join(ROOT, 'web/data'))
    .filter((name) => name.endsWith('-sample.json') || name.endsWith('.json'))
    .map((name) => path.join('web/data', name));

files.push(
    'web/data/issue-resolution-sample.json',
    'data/roadmap/ai-roadmap-report.json'
);

for (const rel of files) {
    const filePath = path.join(ROOT, rel);
    if (!fs.existsSync(filePath)) {
        console.warn('skip missing', rel);
        continue;
    }
    let text = fs.readFileSync(filePath, 'utf8');
    const before = text;
    for (const [pattern, replacement] of pairs) {
        text = text.replace(pattern, replacement);
    }
    if (text !== before) {
        fs.writeFileSync(filePath, text);
        console.log('updated', rel);
    }
}

const reportPath = path.join(ROOT, 'data/roadmap/ai-roadmap-report.json');
if (fs.existsSync(reportPath)) {
    console.log('canonical ai-roadmap baseline:', path.relative(ROOT, reportPath));
}
