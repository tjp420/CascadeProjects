        async function generateRealRoadmap(projectData) {
            // Analyze actual project files to generate roadmap
            const features = [];
            const completed = [];
            const inProgress = [];
            
            // Scan for actual development files and their status
            for (const [path, info] of Object.entries(projectData.files)) {
                if (info.type === 'development') {
                    features.push({
                        name: path,
                        status: info.status || 'planned',
                        priority: info.priority || 'medium',
                        lastModified: info.lastModified
                    });
                    
                    if (info.status === 'completed') completed.push(path);
                    else if (info.status === 'in-progress') inProgress.push(path);
                }
            }
            
            return {
                totalFeatures: features.length,
                completedFeatures: completed.length,
                inProgressFeatures: inProgress.length,
                plannedFeatures: features.length - completed.length - inProgress.length,
                completionRate: ((completed.length / features.length) * 100).toFixed(1) + '%',
                features: features
            };
        }

