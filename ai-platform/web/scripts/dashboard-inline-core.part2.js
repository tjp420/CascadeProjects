        async function detectMockDataPatterns(mockDataFiles) {
            const patterns = [];
            const patternFrequency = {};
            
            // In-house AI pattern detection
            mockDataFiles.forEach(file => {
                file.patterns.forEach(pattern => {
                    if (!patternFrequency[pattern]) {
                        patternFrequency[pattern] = 0;
                    }
                    patternFrequency[pattern]++;
                });
            });
            
            // Analyze patterns and create insights
            Object.entries(patternFrequency).forEach(([pattern, frequency]) => {
                const confidence = Math.min(95, 60 + (frequency * 10));
                patterns.push({
                    name: pattern,
                    frequency: frequency,
                    confidence: confidence,
                    description: `Pattern detected in ${frequency} files with ${confidence}% confidence`,
                    optimization: frequency > 3 ? 'High' : frequency > 1 ? 'Medium' : 'Low'
                });
            });
            
            return patterns.sort((a, b) => b.frequency - a.frequency);
        }

