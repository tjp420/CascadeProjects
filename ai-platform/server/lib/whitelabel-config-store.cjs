'use strict';

/**
 * Whitelabel Partner Branding Store — Per-partner configuration for
 * custom dashboard logos, color themes, report headers, email templates,
 * and domain-based brand routing for sub-tenants.
 *
 * @module whitelabel-config-store
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const logger = require('../lib/app-logger.cjs');

const STORE_PATH = process.env.WHITELABEL_STORE_PATH
  || path.join(__dirname, '../../.simplebeacon', 'whitelabel-configs.json');

let _cache = null;
let _cacheDirty = true;

function readStore() {
  if (_cache && !_cacheDirty) return _cache;
  try {
    const raw = fs.readFileSync(STORE_PATH, 'utf8');
    _cache = JSON.parse(raw);
  } catch {
    _cache = { partners: {} };
  }
  _cacheDirty = false;
  return _cache;
}

function writeStore(store) {
  const dir = path.dirname(STORE_PATH);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  const tmp = STORE_PATH + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(store, null, 2), 'utf8');
  fs.renameSync(tmp, STORE_PATH);
  _cache = store;
  _cacheDirty = false;
}

// ── Default brand values ────────────────────────────────────────────────────

const DEFAULT_BRAND = {
  productName: 'SimpleBeacon',
  tagline: 'AI Compliance, Automated',
  logoUrl: null,
  logoDarkUrl: null,
  faviconUrl: null,
  primaryColor: '#4A90D9',
  secondaryColor: '#36A64F',
  accentColor: '#FF6600',
  backgroundColor: '#0F172A',
  surfaceColor: '#1E293B',
  textColor: '#F1F5F9',
  reportHeader: 'SimpleBeacon Compliance Report',
  reportFooter: 'Generated by SimpleBeacon.ai — EU AI Act Article 50 Disclosure: Outputs may be AI-generated.',
  emailFromName: 'SimpleBeacon',
  emailFromAddress: 'notifications@simplebeacon.ai',
  emailTemplateColor: '#4A90D9',
  customCss: null,
  customDomain: null,
  customSubdomain: null,
  legalName: 'SimpleBeacon AI, Inc.',
  privacyPolicyUrl: null,
  termsUrl: null,
  supportUrl: null,
  helpUrl: null,
};

const BRAND_FIELDS = Object.keys(DEFAULT_BRAND);

// ── CRUD ────────────────────────────────────────────────────────────────────

function createPartner(params) {
  const store = readStore();
  const partnerId = `wl-${crypto.randomBytes(4).toString('hex')}`;
  const now = new Date().toISOString();

  if (!params.name) throw new Error('Partner name is required');
  if (!params.domains || !Array.isArray(params.domains) || params.domains.length === 0) {
    throw new Error('At least one domain is required');
  }

  const brand = { ...DEFAULT_BRAND };
  for (const field of BRAND_FIELDS) {
    if (params[field] !== undefined) brand[field] = params[field];
  }

  const partner = {
    partnerId,
    name: params.name,
    displayName: params.displayName || params.name,
    domains: params.domains.map(d => d.toLowerCase().trim()),
    orgId: params.orgId || null,
    brand,
    enabled: params.enabled !== false,
    createdAt: now,
    updatedAt: now,
    subTenants: [],
  };

  store.partners[partnerId] = partner;
  writeStore(store);
  logger.info(`[Whitelabel] Created partner ${partnerId} (${params.name}) with domains: ${partner.domains.join(', ')}`);
  return partner;
}

function updatePartner(partnerId, updates) {
  const store = readStore();
  const partner = store.partners[partnerId];
  if (!partner) throw new Error(`Partner not found: ${partnerId}`);

  if (updates.name !== undefined) partner.name = updates.name;
  if (updates.displayName !== undefined) partner.displayName = updates.displayName;
  if (updates.domains !== undefined) partner.domains = updates.domains.map(d => d.toLowerCase().trim());
  if (updates.orgId !== undefined) partner.orgId = updates.orgId;
  if (updates.enabled !== undefined) partner.enabled = updates.enabled;

  for (const field of BRAND_FIELDS) {
    if (updates[field] !== undefined) partner.brand[field] = updates[field];
  }

  partner.updatedAt = new Date().toISOString();
  store.partners[partnerId] = partner;
  writeStore(store);
  return partner;
}

function deletePartner(partnerId) {
  const store = readStore();
  if (!store.partners[partnerId]) return false;
  delete store.partners[partnerId];
  writeStore(store);
  logger.info(`[Whitelabel] Deleted partner ${partnerId}`);
  return true;
}

function getPartner(partnerId) {
  const store = readStore();
  return store.partners[partnerId] || null;
}

function getAllPartners() {
  const store = readStore();
  return Object.values(store.partners);
}

function resolveByDomain(domain) {
  const store = readStore();
  const normalized = domain.toLowerCase().trim();
  for (const partner of Object.values(store.partners)) {
    if (!partner.enabled) continue;
    if (partner.domains.includes(normalized)) return partner;
    for (const d of partner.domains) {
      if (normalized.endsWith('.' + d) || normalized === d) return partner;
    }
  }
  return null;
}

function resolveBySubdomain(subdomain) {
  const store = readStore();
  for (const partner of Object.values(store.partners)) {
    if (!partner.enabled) continue;
    if (partner.brand.customSubdomain && partner.brand.customSubdomain.toLowerCase() === subdomain.toLowerCase()) {
      return partner;
    }
  }
  return null;
}

function addSubTenant(partnerId, subTenant) {
  const store = readStore();
  const partner = store.partners[partnerId];
  if (!partner) throw new Error(`Partner not found: ${partnerId}`);
  if (!subTenant.orgId) throw new Error('subTenant orgId is required');
  partner.subTenants.push({
    orgId: subTenant.orgId,
    name: subTenant.name || subTenant.orgId,
    addedAt: new Date().toISOString(),
  });
  partner.updatedAt = new Date().toISOString();
  writeStore(store);
  return partner;
}

function removeSubTenant(partnerId, orgId) {
  const store = readStore();
  const partner = store.partners[partnerId];
  if (!partner) throw new Error(`Partner not found: ${partnerId}`);
  partner.subTenants = partner.subTenants.filter(st => st.orgId !== orgId);
  partner.updatedAt = new Date().toISOString();
  writeStore(store);
  return partner;
}

function getStats() {
  const store = readStore();
  const partners = Object.values(store.partners);
  return {
    totalPartners: partners.length,
    activePartners: partners.filter(p => p.enabled).length,
    totalDomains: partners.reduce((sum, p) => sum + p.domains.length, 0),
    totalSubTenants: partners.reduce((sum, p) => sum + p.subTenants.length, 0),
  };
}

// ── CSS Generation ──────────────────────────────────────────────────────────

function generateBrandCss(brand) {
  const lines = [
    ':root {',
    `  --brand-primary: ${brand.primaryColor};`,
    `  --brand-secondary: ${brand.secondaryColor};`,
    `  --brand-accent: ${brand.accentColor};`,
    `  --brand-background: ${brand.backgroundColor};`,
    `  --brand-surface: ${brand.surfaceColor};`,
    `  --brand-text: ${brand.textColor};`,
    `  --brand-product-name: "${brand.productName}";`,
    `  --brand-tagline: "${brand.tagline}";`,
    `  --brand-report-header: "${brand.reportHeader}";`,
    '}',
  ];

  if (brand.customCss) {
    lines.push('', brand.customCss);
  }

  return lines.join('\n');
}

function getBrandCss(partnerId) {
  const partner = getPartner(partnerId);
  if (!partner) return null;
  return generateBrandCss(partner.brand);
}

function resolveBrandCssByDomain(domain) {
  const partner = resolveByDomain(domain);
  if (!partner) return null;
  return { partnerId: partner.partnerId, css: generateBrandCss(partner.brand), brand: partner.brand };
}

module.exports = {
  DEFAULT_BRAND,
  BRAND_FIELDS,
  createPartner,
  updatePartner,
  deletePartner,
  getPartner,
  getAllPartners,
  resolveByDomain,
  resolveBySubdomain,
  addSubTenant,
  removeSubTenant,
  getStats,
  generateBrandCss,
  getBrandCss,
  resolveBrandCssByDomain,
};
