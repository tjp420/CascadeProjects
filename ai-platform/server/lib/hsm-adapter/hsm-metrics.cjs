/**
 * Increment a counter.
 * @param {string} name - counter name
 * @param {number} [value=1] - increment amount
 */
function incrementCounter(name, value = 1) {
  if (counters[name] !== undefined) {
    counters[name] += value;
  }
}

/**
 * Observe a latency value in a histogram.
 * @param {string} name - histogram name
 * @param {number} durationMs - observed duration in milliseconds
 */
function observeHistogram(name, durationMs) {
  const h = histograms[name];
  if (!h) return;
  h.sum += durationMs;
  h.count++;
  for (let i = 0; i < h.buckets.length; i++) {
    if (durationMs <= h.buckets[i]) {
      h.counts[i]++;
      return;
    }
  }
  // Overflow bucket (+Inf)
  h.counts[h.counts.length - 1]++;
}

/**
 * Reset all metrics to zero. Primarily for testing.
 */
function reset() {
  for (const key of Object.keys(counters)) {
    counters[key] = 0;
  }
  for (const key of Object.keys(histograms)) {
    histograms[key].counts.fill(0);
    histograms[key].sum = 0;
    histograms[key].count = 0;
  }
}

/**
 * Get all metrics as a flat object (for programmatic access).
 * @returns {object} metric name -> value
 */
function getMetrics() {
  const result = { ...counters };
  for (const [name, h] of Object.entries(histograms)) {
    result[`${name}_count`] = h.count;
    result[`${name}_sum`] = h.sum;
    for (let i = 0; i < h.buckets.length; i++) {
      result[`${name}_bucket{le="${h.buckets[i]}"}`] = h.counts[i];
    }
    result[`${name}_bucket{le="+Inf"}`] = h.count;
  }
  return result;
}

/**
 * Render metrics in Prometheus exposition format.
 * @returns {string} Prometheus text format
 */
function renderPrometheus() {
  const lines = [];

  // Counters
  for (const [name, value] of Object.entries(counters)) {
    const meta = META[name];
    if (!meta) continue;
    lines.push(`# HELP ${name} ${meta.help}`);
    lines.push(`# TYPE ${name} ${meta.type}`);
    lines.push(`${name} ${value}`);
  }

  // Histograms
  for (const [name, h] of Object.entries(histograms)) {
    const meta = META[name];
    if (!meta) continue;
    lines.push(`# HELP ${name} ${meta.help}`);
    lines.push(`# TYPE ${name} ${meta.type}`);
    // Cumulative bucket counts
    let cumulative = 0;
    for (let i = 0; i < h.buckets.length; i++) {
      cumulative += h.counts[i];
      lines.push(`${name}_bucket{le="${h.buckets[i]}"} ${cumulative}`);
    }
    cumulative += h.counts[h.counts.length - 1];
    lines.push(`${name}_bucket{le="+Inf"} ${cumulative}`);
    lines.push(`${name}_sum ${h.sum}`);
    lines.push(`${name}_count ${h.count}`);
  }

  return lines.join('\n') + '\n';
}

/**
 * Sync SIEM broker metrics into the HSM metrics registry.
 *
 * Pulls the broker's internal counters (processed, dropped, bypassed,
 * tokens consumed, current token bucket capacity) into the platform's
 * Prometheus exposition surface so they appear in /metrics output.
 *
 * @param {object} broker - SiemSecurityBroker instance with getMetrics()
 */
function updateSiemMetrics(broker) {
  if (!broker || typeof broker.getMetrics !== 'function') return;
  const m = broker.getMetrics();
  if (m.siem_events_processed_total !== undefined) {
    counters.siem_events_processed_total = m.siem_events_processed_total;
  }
  if (m.siem_events_dropped_total !== undefined) {
    counters.siem_events_dropped_total = m.siem_events_dropped_total;
  }
  if (m.siem_events_bypassed_total !== undefined) {
    counters.siem_events_bypassed_total = m.siem_events_bypassed_total;
  }
  if (m.siem_tokens_consumed_total !== undefined) {
    counters.siem_tokens_consumed_total = m.siem_tokens_consumed_total;
  }
  if (m.currentTokens !== undefined) {
    counters.siem_token_bucket_current = m.currentTokens;
  }
}

