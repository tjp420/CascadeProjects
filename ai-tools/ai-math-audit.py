# ── CLI ────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Deterministic mathematical audit of AI model numerical logs"
    )
    parser.add_argument("--log-file", help="Single JSON or JSONL log file")
    parser.add_argument("--log-dir", help="Directory containing JSON/JSONL logs")
    parser.add_argument("--reference", help="Reference embedding baseline JSON")
    parser.add_argument("--output", help="Write audit report to this JSON file")
    parser.add_argument("--verbose", action="store_true", help="Print full findings to stdout")
    parser.add_argument("--viz-dir", dest="viz_dir", help="Directory to write visualization PNGs")
    parser.add_argument("--format", choices=["json", "html"], default="json", help="Report output format")

    # Threshold tunables
    parser.add_argument("--entropy-threshold", type=float, default=2.5)
    parser.add_argument("--diag-dominance-threshold", type=float, default=0.6)
    parser.add_argument("--z-threshold", type=float, default=3.0)
    parser.add_argument("--saturation-threshold", type=float, default=0.95)
    parser.add_argument("--cosine-min", type=float, default=0.70)
    parser.add_argument("--euclidean-max", type=float, default=2.5)
    parser.add_argument("--loss-spike", type=float, default=2.0)
    parser.add_argument("--grad-norm-max", type=float, default=10.0)

    args = parser.parse_args()

    source = args.log_file or args.log_dir
    if not source:
        parser.error("Provide --log-file or --log-dir")
    if not Path(source).exists():
        print(f"Error: path not found: {source}", file=sys.stderr)  # simplebeacon-ignore debug-artifact — CLI error output
        sys.exit(1)

    report = run_audit(source, args)

    if args.output:
        if args.format == "html":
            _write_html_report(report, args.output)
        else:
            with open(args.output, "w", encoding="utf-8") as fh:
                json.dump(report, fh, indent=2, ensure_ascii=False)
        print(f"Report written to {args.output}")

    summary = report["summary"]
    print(f"\n=== AI Math Audit Report ===")
    print(f"Source : {report['source']}")
    print(f"Time   : {report['audit_timestamp']}")
    print(f"Findings: {summary['total_findings']} total")
    print(f"  Critical : {summary['critical']}")
    print(f"  High     : {summary['high']}")
    print(f"  Medium   : {summary['medium']}")
    print(f"  Low      : {summary['low']}")
    print(f"Breakdown:")
    print(f"  Attention : {summary['attention_findings']}")
    print(f"  Activation: {summary['activation_findings']}")
    print(f"  Drift     : {summary['drift_findings']}")
    print(f"  Trace     : {summary['trace_findings']}")

    if args.verbose and report["findings"]:
        print("\n--- Detailed Findings ---")
        for f in report["findings"]:
            print(f"\n[{f['severity'].upper()}] {f['type']}")
            for k, v in f.items():
                if k != "type" and k != "severity":
                    print(f"  {k}: {v}")

    # Exit non-zero if any critical findings
    if summary["critical"] > 0:
        sys.exit(2)
    if summary["high"] > 0:
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    main()
