#!/usr/bin/env node
'use strict';

/**
 * Bundle scan-worker.js + its ES module imports into a single self-contained
 * file with no `import` statements so it works as a classic Worker in Firefox
 * and fully offline (no fetch needed for dependencies).
 *
 * Output: dashboard-web/assets/scan-worker-bundled.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_WORKER = path.join(ROOT, 'js-es2018', 'workers', 'scan-worker.js');
const SRC_WASM_BRIDGE = path.join(ROOT, 'js-es2018', 'workers', 'scan-wasm-bridge.js');
const SRC_IGNORE_BROWSER = path.join(ROOT, 'js-es2018', 'utils-lib', 'simplebeaconignore.browser.js');
const DIST_ASSETS = path.join(ROOT, 'assets');
const OUT_PATH = path.join(DIST_ASSETS, 'scan-worker-bundled.js');

function read(p) {
  if (!fs.existsSync(p)) throw new Error(`Missing source file: ${p}`);
  return fs.readFileSync(p, 'utf8');
}

/**
 * Strip `export` keywords from a module body so it can be concatenated
 * into a classic worker. We convert `export function foo()` → `function foo()`,
 * `export const foo` → `const foo`, `export class Foo` → `class Foo`,
 * `export { a, b }` → removed (names already declared above),
 * `export async function foo()` → `async function foo()`,
 * `export default ...` → stripped.
 */
function stripExports(code) {
  return (
    code
      // export { a, b, c };  → remove entirely
      .replace(/^\s*export\s*\{[^}]*\}\s*;?\s*$/gm, '')
      // export default ...;  → remove the line
      .replace(/^\s*export\s+default\s+.*$/gm, '')
      // export { a, b } from '...';  → remove
      .replace(/^\s*export\s*\{[^}]*\}\s+from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
      // export const/let/var/function/class/async function
      .replace(/^\s*export\s+(const|let|var|function|class|async\s+function)\b/gm, '$1')
      // trailing `export { foo };` blocks
      .replace(/\n\s*export\s*\{[^}]*\}\s*;?\s*\n/g, '\n')
  );
}

/**
 * Remove `import ... from '...'` lines entirely.
 * The imported bindings become locally-defined after concatenation.
 */
function stripImports(code) {
  return (
    code
      // import { a, b } from '...';
      .replace(/^\s*import\s+\{[^}]*\}\s+from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
      // import defaultName from '...';
      .replace(/^\s*import\s+\w+\s+from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
      // import '...';
      .replace(/^\s*import\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
      // import * as ns from '...';
      .replace(/^\s*import\s+\*\s+as\s+\w+\s+from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
  );
}

/**
 * Remove `import.meta.url` references — replace with a placeholder.
 * In the bundled worker there's no module URL, so use self.location.href.
 */
function replaceImportMeta(code) {
  return code.replace(/import\.meta\.url/g, 'self.location.href');
}

/**
 * Neutralize top-level `new URL(...)` calls that would throw in a Blob worker
 * context (relative paths can't resolve against a blob: URL). Wrap them in
 * try/catch so they don't crash the worker on load.
 */
function safeTopLevelUrls(code) {
  // Match: const X = new URL('...', self.location.href);
  // Replace with: const X = (() => { try { return new URL('...', self.location.href); } catch { return null; } })();
  return code.replace(
    /const\s+(\w+)\s*=\s*new URL\(([^,]+),\s*self\.location\.href\)/g,
    'const $1 = (() => { try { return new URL($2, self.location.href); } catch { return null; } })()'
  );
}

function main() {
  if (!fs.existsSync(DIST_ASSETS)) {
    fs.mkdirSync(DIST_ASSETS, { recursive: true });
  }

  const workerCode = read(SRC_WORKER);
  const bridgeCode = read(SRC_WASM_BRIDGE);
  const ignoreCode = read(SRC_IGNORE_BROWSER);

  // Strip module syntax from each file
  const bridgeStripped = safeTopLevelUrls(stripImports(stripExports(replaceImportMeta(bridgeCode))));
  const ignoreStripped = stripImports(stripExports(ignoreCode));
  const workerStripped = stripImports(workerCode);

  // Remove duplicate const declarations that appear in both bridge and worker.
  // The worker defines its own SEVERITY_MAP, CREDENTIAL_ALLOWLIST, IGNORE_LINE_RE
  // which overlap with the bridge. Keep the worker versions (they're more complete)
  // by stripping the bridge's copies.
  const DUPLICATE_BRIDGE_DECLS = [
    /const SEVERITY_MAP\s*=\s*\{[^}]*\}\s*;/,
    /const CREDENTIAL_ALLOWLIST\s*=\s*\/[^\/]+\/[a-z]*\s*;/,
    /const IGNORE_LINE_RE\s*=\s*\/[^\/]+\/[a-z]*\s*;/,
  ];
  let bridgeDeduped = bridgeStripped;
  for (const re of DUPLICATE_BRIDGE_DECLS) {
    bridgeDeduped = bridgeDeduped.replace(re, '/* (deduped: defined in worker body below) */');
  }

  // Concatenate: ignore utils first, then wasm bridge, then the worker body
  const bundled = [
    '/**',
    ' * scan-worker-bundled.js — self-contained browser scan worker.',
    ' * Generated by scripts/bundle-worker.cjs — do not edit by hand.',
    ' * This file has no ES module imports so it works as a classic Worker',
    ' * in Firefox and fully offline (no fetch needed for dependencies).',
    ' */',
    '',
    '// ===== simplebeaconignore.browser.js (inlined) =====',
    ignoreStripped.trim(),
    '',
    '// ===== scan-wasm-bridge.js (inlined, deduped) =====',
    bridgeDeduped.trim(),
    '',
    '// ===== scan-worker.js (inlined) =====',
    workerStripped.trim(),
    '',
  ].join('\n');

  fs.writeFileSync(OUT_PATH, bundled, 'utf8');

  const sizeKb = Math.round(bundled.length / 1024);
  const importCount = (bundled.match(/^\s*import\s/gm) || []).length;
  const exportCount = (bundled.match(/^\s*export\s/gm) || []).length;

  console.log(`[bundle-worker] Wrote ${OUT_PATH} (${sizeKb} KB)`);
  console.log(`[bundle-worker] Remaining import statements: ${importCount}`);
  console.log(`[bundle-worker] Remaining export statements: ${exportCount}`);

  if (importCount > 0) {
    console.warn('[bundle-worker] WARNING: import statements remain — Firefox classic worker will fail!');
    process.exit(1);
  }
  if (exportCount > 0) {
    console.warn(
      '[bundle-worker] WARNING: export statements remain — these are no-ops in classic workers but should be stripped'
    );
  }
}

if (require.main === module) {
  main();
}

module.exports = { main };
